// Writes src/mcp/consent-template.ts from Design's design/screens/oauth-consent.html
// (its top comment stripped), so the Worker bundles it as a string. Run by
// `pnpm build`; the file is committed and test/mcp.oauth.test.ts fails when stale.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { stripTemplateComment } from "../src/mcp/template.ts";

const root = path.join(import.meta.dirname, "..");
const src = path.join(
  root,
  "..",
  "..",
  "design",
  "screens",
  "oauth-consent.html",
);
const out = path.join(root, "src", "mcp", "consent-template.ts");
const html = stripTemplateComment(readFileSync(src, "utf8"));
// A template literal keeps the file readable and stable under the formatter.
const literal = html
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");
writeFileSync(
  out,
  `// Generated by scripts/emit-consent-template.ts from design/screens/oauth-consent.html. Do not edit.\nexport const CONSENT_TEMPLATE = \`${literal}\`;\n`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
