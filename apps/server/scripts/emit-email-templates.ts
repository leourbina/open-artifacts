// Writes src/email/email-templates.ts from Design's design/emails/{invite,share}
// .{html,txt}, so the Worker bundles them as strings (no runtime reads). Run by
// `pnpm build`; the file is committed and test/email.templates.test.ts fails
// when stale.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const dir = path.join(root, "..", "..", "design", "emails");
const out = path.join(root, "src", "email", "email-templates.ts");
// A template literal keeps the file readable and stable under the formatter.
const literal = (s: string) =>
  s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const parts = [
  ["INVITE_HTML", "invite.html"],
  ["INVITE_TXT", "invite.txt"],
  ["SHARE_HTML", "share.html"],
  ["SHARE_TXT", "share.txt"],
].map(
  ([name, file]) =>
    `export const ${name} = \`${literal(readFileSync(path.join(dir, file as string), "utf8"))}\`;\n`,
);
writeFileSync(
  out,
  `// Generated by scripts/emit-email-templates.ts from design/emails/. Do not edit.\n${parts.join("\n")}`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
