// Writes src/mcp/upgrade.generated.ts: the /upgrade.md template with
// {{tokens}} for the per-instance values. Run by `pnpm build`; the file is
// committed and test/upgrade.test.ts fails when it is stale.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { renderUpgradeTemplate } from "../src/mcp/upgrade-template.ts";

const out = path.join(
  import.meta.dirname,
  "..",
  "src",
  "mcp",
  "upgrade.generated.ts",
);
const tpl = renderUpgradeTemplate();
/** In the ETag, so a template change is a new ETag even at the same VERSION. */
const hash = createHash("sha256").update(tpl).digest("hex").slice(0, 8);
// A template literal keeps the file readable and stable under the formatter.
const literal = tpl
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");
writeFileSync(
  out,
  `// Generated by scripts/emit-upgrade.ts from src/mcp/upgrade-template.ts. Do not edit.\nexport const UPGRADE_HASH = "${hash}";\nexport const UPGRADE_TEMPLATE = \`${literal}\`;\n`,
);
console.log(
  `wrote upgrade template (${tpl.split("\n").length} lines) to ${path.relative(process.cwd(), out)}`,
);
