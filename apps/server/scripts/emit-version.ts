// Writes src/version.gen.ts (VERSION, COMMIT) from the root package.json and
// git, by the rule in scripts/version-rule.ts. The file is gitignored: the
// package's build, test, test:cpu, bench and typecheck scripts run this first,
// so every deploy, bundle and test sees it. Writes only on change.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { instanceVersion } from "./version-rule.ts";

const root = path.join(import.meta.dirname, "..", "..", "..");
const out = path.join(import.meta.dirname, "..", "src", "version.gen.ts");

const git = (args: string[]): string | null => {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
};

const { version } = JSON.parse(
  readFileSync(path.join(root, "package.json"), "utf8"),
) as { version: string };
const sha = git(["rev-parse", "--short=7", "HEAD"]) || null;
const tagOut = sha ? git(["tag", "--points-at", "HEAD"]) : null;
const tags = tagOut === null ? null : tagOut.split("\n").filter(Boolean);
const v = instanceVersion({ version, tags, sha });
const body = `// Generated by scripts/emit-version.ts. Do not edit.
export const VERSION = ${JSON.stringify(v)};
export const COMMIT = ${JSON.stringify(sha ?? "")};
`;
if (!existsSync(out) || readFileSync(out, "utf8") !== body)
  writeFileSync(out, body);
console.log(`version ${v}`);
