import type { Ctx, Step } from "../step.ts";
import { zoneOf } from "./prereqs.ts";

export const DASH_SENDING =
  "https://dash.cloudflare.com/?to=/:account/email-service/sending";
const DOH = "https://cloudflare-dns.com/dns-query";
const CF_MX = /^route[123]\.mx\.cloudflare\.net$/i;
const CF_SPF = "include:_spf.mx.cloudflare.net";

/** What "Onboard Domain" adds for `d` (the DKIM key is Cloudflare-generated). */
export const records = (d: string) => [
  {
    type: "MX",
    name: `cf-bounce.${d}`,
    content:
      "route1.mx.cloudflare.net, route2.mx.cloudflare.net, route3.mx.cloudflare.net",
  },
  { type: "TXT", name: `cf-bounce.${d}`, content: `v=spf1 ${CF_SPF} ~all` },
  {
    type: "TXT",
    name: `cf-bounce._domainkey.${d}`,
    content: "v=DKIM1; ... (key generated by Cloudflare)",
  },
  { type: "TXT", name: `_dmarc.${d}`, content: "v=DMARC1; p=reject;" },
];

/** TXT chunks joined and unquoted; MX as a bare host without the trailing dot. */
const norm = (type: string, v: string) =>
  type === "TXT"
    ? v.replace(/"\s+"/g, "").replace(/^"|"$/g, "")
    : (v.split(" ").at(-1) ?? "").replace(/\.$/, "");

/** Contexts whose token can't read DNS records: they use DoH. */
const viaDoh = new WeakSet<Ctx>();

/**
 * Record values for `name`: the zone's dns_records API, else public DNS over
 * HTTPS (wrangler's OAuth login has Zone Read but not DNS Read).
 */
async function lookup(ctx: Ctx, zoneId: string, name: string, type: string) {
  if (!viaDoh.has(ctx))
    try {
      const q = `/zones/${zoneId}/dns_records?type=${type}&name=${encodeURIComponent(name)}`;
      const rs = await ctx.api.all<{ content: string }>(q);
      return rs.map((r) => norm(type, r.content));
    } catch (e) {
      const s = (e as { status?: number }).status;
      if (s !== 401 && s !== 403) throw e;
      viaDoh.add(ctx);
    }
  const url = `${DOH}?name=${encodeURIComponent(name)}&type=${type}`;
  const res = await ctx.deps.fetch(url, {
    headers: { accept: "application/dns-json" },
  });
  if (!res.ok)
    throw new Error(`DNS lookup ${name} ${type}: HTTP ${res.status}`);
  const { Answer } = (await res.json()) as {
    Answer?: { type: number; data: string }[];
  };
  const code = type === "MX" ? 15 : 16;
  return (Answer ?? [])
    .filter((a) => a.type === code)
    .map((a) => norm(type, a.data));
}

/** The onboarding records not (yet) in DNS. */
async function missing(ctx: Ctx, zoneId: string, d: string) {
  const txt = (n: string) => lookup(ctx, zoneId, n, "TXT");
  const mx = await lookup(ctx, zoneId, `cf-bounce.${d}`, "MX");
  const spf = await txt(`cf-bounce.${d}`);
  const dkim = await txt(`cf-bounce._domainkey.${d}`);
  const dmarc = await txt(`_dmarc.${d}`);
  return [
    !mx.some((h) => CF_MX.test(h)) && `MX cf-bounce.${d}`,
    !spf.some((t) => t.includes(CF_SPF)) && `SPF cf-bounce.${d}`,
    !dkim.some((t) => /^v=DKIM1/i.test(t)) && `DKIM cf-bounce._domainkey.${d}`,
    !dmarc.some((t) => /^v=DMARC1/i.test(t)) && `DMARC _dmarc.${d}`,
  ].filter((x): x is string => Boolean(x));
}

async function zone(ctx: Ctx, accountId: string, d: string) {
  const z = await zoneOf(ctx, accountId, d);
  if (!z)
    throw new Error(
      `email domain ${d} is not in any active zone of account ${accountId}; Email Sending needs Cloudflare DNS (pass another --email-domain)`,
    );
  return z;
}

const yes = (a: string) => /^y(es)?$/i.test(a);

/**
 * Team installs send invites with Email Sending (Workers Paid only; prereqs
 * decides whether email is on). The domain is onboarded by a human in the
 * dashboard (no API); this step checks for a conflict with existing mail
 * first, then verifies the onboarding DNS.
 */
export const email: Step = {
  name: "email",
  async check(state, ctx) {
    const { team, email: on, emailDomain: d } = ctx.opts;
    if (!on || !d) {
      ctx.notes.push(team ? "email off (--no-email)" : "solo: no email");
      return "done";
    }
    const z = await zone(ctx, state.accountId ?? "", d);
    // The apex is re-confirmed on every run (apply), onboarded or not.
    if (d === z.name) {
      ctx.notes.push(`${d} is the zone apex: confirmed on every run`);
      return "todo";
    }
    const gone = await missing(ctx, z.id, d);
    if (gone.length) {
      ctx.notes.push(
        `${d} not onboarded for Email Sending: missing ${gone.join(", ")}`,
      );
      return "todo";
    }
    ctx.notes.push(`sending domain ${d} onboarded`);
    return "done";
  },
  async apply(state, ctx) {
    const d = ctx.opts.emailDomain ?? "";
    const accountId = state.accountId ?? "";
    const z = await zone(ctx, accountId, d);
    if (d === z.name && !ctx.opts.emailDomainFlag)
      return {
        status: "action_required",
        message: `the saved sending domain ${d} is the zone apex, which setup never reuses silently: pass --email-domain ${d} again (and confirm), or use a subdomain such as mail.${ctx.opts.appHost}`,
        data: { domain: d },
      };
    const conflict = await conflictOf(ctx, z, d);
    if (conflict && !ctx.opts.yesEmailDomain) {
      const data = { domain: d, conflicts: conflict.has };
      if (!ctx.opts.interactive)
        return {
          status: "action_required",
          message: `${conflict.why} Pass --yes-email-domain to confirm, or pick another --email-domain.`,
          data,
        };
      if (!yes(await ctx.deps.prompt(`${conflict.why} Use ${d} anyway? [y/N]`)))
        return {
          status: "action_required",
          message: `${d} not confirmed; rerun with another --email-domain`,
          data,
        };
    }
    const gone = await missing(ctx, z.id, d);
    if (!gone.length) {
      ctx.notes.push(`sending domain ${d} onboarded`);
      return undefined;
    }
    const recs = records(d);
    const list = recs.map((r) => `${r.type} ${r.name} ${r.content}`).join("; ");
    return {
      status: "action_required",
      message: `Onboard ${d} for Email Sending (a dashboard step; there is no API): open ${DASH_SENDING}, select Onboard Domain and pick ${d}. It adds: ${list}. Then rerun setup; it re-checks DNS (usually 5-15 minutes).`,
      data: {
        domain: d,
        dashboard: DASH_SENDING,
        missing: gone,
        records: recs,
      },
    };
  },
};

/** Existing mail at `d` that onboarding could disturb; undefined when clear. */
async function conflictOf(
  ctx: Ctx,
  z: { id: string; name: string },
  d: string,
) {
  const mx = await lookup(ctx, z.id, d, "MX");
  const spf = (await lookup(ctx, z.id, d, "TXT")).filter(
    (t) => /^v=spf1/i.test(t) && !t.includes(CF_SPF),
  );
  const apex = d === z.name;
  // At the apex any MX is someone's mail; below it, Cloudflare's own is fine.
  const foreign = apex ? mx : mx.filter((h) => !CF_MX.test(h));
  if (!foreign.length && !spf.length) return undefined;
  const has = [
    ...foreign.map((h) => `MX ${h}`),
    ...spf.map((t) => `SPF "${t}"`),
  ].join(", ");
  const noDmarc =
    apex &&
    foreign.length > 0 &&
    !(await lookup(ctx, z.id, `_dmarc.${d}`, "TXT")).length;
  const sub = `mail.${ctx.opts.appHost}`;
  const warn = noDmarc
    ? ` WARNING: ${d} is the zone apex and has no _dmarc record. Onboarding adds "_dmarc.${d}" = "v=DMARC1; p=reject;", so receivers may reject mail your current provider sends as @${d}. Use a subdomain such as ${sub} instead.`
    : apex
      ? ` ${d} is the zone apex; a subdomain such as ${sub} is safer.`
      : "";
  return {
    has,
    why: `${d} already has mail records elsewhere (${has}).${warn} Onboarding it for Email Sending adds cf-bounce records and _dmarc.${d}.`,
  };
}
